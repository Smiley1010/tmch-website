
import puppeteer from "puppeteer";
import http from "node:http";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const DIST_DIR = path.resolve(__dirname, "../dist");
const API_BASE =
  process.env.VITE_API_URL || "http://localhost:5000/api";

const PUBLIC_ROUTES = [
  "/",
  "/about",
  "/services",
  "/projects",
  "/contact",
  "/blog",
];

const MIME_TYPES = {
  ".html": "text/html",
  ".js": "text/javascript",
  ".css": "text/css",
  ".json": "application/json",
  ".png": "image/png",
  ".jpg": "image/jpeg",
  ".jpeg": "image/jpeg",
  ".webp": "image/webp",
  ".avif": "image/avif",
  ".svg": "image/svg+xml",
  ".woff": "font/woff",
  ".woff2": "font/woff2",
};

function startServer() {
  const server = http.createServer((req, res) => {
    const pathname = decodeURIComponent(
      new URL(req.url, "http://localhost").pathname
    );

    let requestedPath = path.resolve(
      DIST_DIR,
      "." + pathname
    );
const normalizedDist = path.resolve(DIST_DIR);
const normalizedRequested = path.resolve(requestedPath);

if (
  normalizedRequested !== normalizedDist &&
  !normalizedRequested.startsWith(normalizedDist + path.sep)
) {
  res.writeHead(403);
  return res.end("Forbidden");
}

    if (
      fs.existsSync(requestedPath) &&
      fs.statSync(requestedPath).isDirectory()
    ) {
      requestedPath = path.join(requestedPath, "index.html");
    }

    if (
      !fs.existsSync(requestedPath) ||
      !fs.statSync(requestedPath).isFile()
    ) {
      requestedPath = path.join(DIST_DIR, "index.html");
    }

    const extension = path.extname(requestedPath);

    res.writeHead(200, {
      "Content-Type":
        MIME_TYPES[extension] || "application/octet-stream",
    });

    fs.createReadStream(requestedPath).pipe(res);
  });

  return new Promise((resolve, reject) => {
    server.once("error", reject);

    server.listen(4173, "127.0.0.1", () => {
      resolve({
        server,
        url: "http://127.0.0.1:4173",
      });
    });
  });
}

async function getPublishedArticles() {
  console.log("Fetching published articles...");

  const response = await fetch(`${API_BASE}/articles/public`);

  if (!response.ok) {
    throw new Error(
      `Articles API returned status ${response.status}`
    );
  }

  const data = await response.json();

  return Array.isArray(data.articles) ? data.articles : [];
}

function getOutputPath(route) {
  if (route === "/") {
    return path.join(DIST_DIR, "index.html");
  }

  return path.join(
    DIST_DIR,
    route.replace(/^\/+|\/+$/g, ""),
    "index.html"
  );
}

async function renderRoute(browser, baseUrl, route, type = "page") {
  const page = await browser.newPage();

  page.on("pageerror", (error) => {
  console.log("BROWSER PAGE ERROR:", error.message);
});

page.on("console", (message) => {
  if (message.type() === "error") {
    console.log("BROWSER CONSOLE ERROR:", message.text());
  }
});

page.on("requestfailed", (request) => {
  console.log(
    "FAILED REQUEST:",
    request.url(),
    request.failure()?.errorText
  );
});

  try {
    page.setDefaultNavigationTimeout(60000);

    console.log(`Rendering: ${route}`);

    await page.goto(`${baseUrl}${route}`, {
      waitUntil: "networkidle2",
      timeout: 60000,
    });

    if (type === "article") {
      await page.waitForFunction(
        () =>
          document.querySelector(".blog-article-header h1") ||
          document.querySelector(".blog-not-found"),
        { timeout: 60000 }
      );

      // Wait for article SEO metadata to be generated by React.
await page.waitForFunction(
  () => {
    const title = document.title;
    const description = document.querySelector(
      'meta[name="description"]'
    );
    const canonical = document.querySelector(
      'link[rel="canonical"]'
    );
    const ogTitle = document.querySelector(
      'meta[property="og:title"]'
    );
    const structuredData = document.querySelector(
      'script[type="application/ld+json"]'
    );

    return (
      title &&
      title !== "tmch-website" &&
      description?.content &&
      canonical?.href &&
      ogTitle?.content &&
      structuredData
    );
  },
  { timeout: 30000 }
);

      if (await page.$(".blog-not-found")) {
        throw new Error(`Article failed to render: ${route}`);
      }
    }

if (type === "blog") {
  await new Promise((resolve) => setTimeout(resolve, 8000));

  const diagnostics = await page.evaluate(() => ({
    url: window.location.href,
    title: document.title,
    bodyText: document.body.innerText.slice(0, 2000),
    rootHTML: document.querySelector("#root")?.innerHTML.slice(0, 2000),
    featuredExists: !!document.querySelector(".blog-featured"),
    statusExists: !!document.querySelector(".blog-status"),
  }));

  console.log("\nBLOG PAGE DIAGNOSTICS:");
  console.log(JSON.stringify(diagnostics, null, 2));

  if (
    !diagnostics.featuredExists &&
    !diagnostics.statusExists
  ) {
    throw new Error(
      "Blog page rendered without the expected blog elements. Check the diagnostics above."
    );
  }
}
    // Give React time to finish updating the document.
    await page.evaluate(
      () => new Promise((resolve) => requestAnimationFrame(resolve))
    );

    const html = await page.content();
    const outputPath = getOutputPath(route);

    fs.mkdirSync(path.dirname(outputPath), {
      recursive: true,
    });

    fs.writeFileSync(outputPath, html, "utf8");

    console.log(`Saved: ${outputPath}`);
  } finally {
    await page.close();
  }
}

async function main() {
  if (!fs.existsSync(path.join(DIST_DIR, "index.html"))) {
    throw new Error(
      "dist/index.html not found. Run npm run build first."
    );
  }

  const articles = await getPublishedArticles();

  console.log(`Found ${articles.length} published articles.`);

  const { server, url } = await startServer();

  let browser;

  try {
    browser = await puppeteer.launch({
      headless: true,
      timeout: 60000,
      protocolTimeout: 120000,
      args: [
        "--no-sandbox",
        "--disable-setuid-sandbox",
        "--disable-dev-shm-usage",
        "--disable-gpu",
        "--no-zygote",
        "--single-process",
      ],
    });

    for (const route of PUBLIC_ROUTES) {
      await renderRoute(
        browser,
        url,
        route,
        route === "/blog" ? "blog" : "page"
      );
    }

    for (const article of articles) {
      if (!article.slug || !/^[a-zA-Z0-9_-]+$/.test(article.slug)) {
        console.warn("Skipping invalid article slug:", article.slug);
        continue;
      }

      const route = `/blog/${encodeURIComponent(article.slug)}`;

      await renderRoute(browser, url, route, "article");
    }

    console.log("\nPrerendering completed successfully.");

  } finally {
    if (browser) {
      await browser.close();
    }

    await new Promise((resolve) => server.close(resolve));
  }
}

main().catch((error) => {
  console.error("\nPrerendering failed:", error);
  process.exitCode = 1;
});
